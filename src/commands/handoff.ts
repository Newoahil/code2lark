function buildHandoffManifest(packagePath: string): HandoffManifest {
  const service = readJsonFile<ServiceManifest>(path.join(packagePath, "manifest", "service_manifest.json"));
  const fileSet = buildHandoffFileSet(packagePath);
  const recommendedFiles = fileSet.recommended.map(([filePath, reason]) => fileRow(packagePath, filePath, reason));
  const optionalEvidenceFiles = fileSet.optional.map(([filePath, reason]) => fileRow(packagePath, filePath, reason));
  const excludedPaths = fileSet.excluded.map(([filePath, reason]) => fileRow(packagePath, filePath, reason));
  const warnings = buildWarnings(recommendedFiles, excludedPaths);

  return {
    schema_version: "0.1",
    generated_at: new Date().toISOString(),
    package_path: packagePath,
    target_service: service.service.name,
    recommended_files: recommendedFiles,
    optional_evidence_files: optionalEvidenceFiles,
    excluded_paths: excludedPaths,
    warnings,
    next_steps: [
      "Copy recommended files and directories, excluding all excluded paths.",
      "Or run `handoff --copy-to <empty-dir>` to create a sanitized transfer directory automatically.",
      "`handoff --copy-to` scans copied text files for known local secret values and refuses the copy if one is found.",
      "Run `handoff --check` on the sanitized directory; it also rejects missing configure dry-run guidance, missing init-local guidance, missing permission confirmation summaries, missing doctor live-target gate guidance, stale package path references, non-strict configure commands, and unredacted manual evidence rows in shared Level 2 drafts.",
      "Share real Feishu secrets through a secure channel, not in the package.",
      "Run `npm install` and `npm run build` inside `bot-runtime` after transfer.",
      "Run `readiness`, `verify --level2`, `evidence`, and `doctor --probe-target --gate` from the target environment before final sign-off.",
    ],
  };
}

function buildHandoffFileSet(packagePath: string): HandoffFileSet {
  return {
    recommended: requiredHandoffFiles(packagePath),
    optional: optionalHandoffFiles(packagePath),
    excluded: Array.from(EXCLUDED_PATHS),
  };
}

function requiredHandoffFiles(packagePath: string): HandoffFileDefinition[] {
  const rows = new Map<string, string>(BASE_RECOMMENDED_FILES);
  const imageMetaPath = "manifest/image_agent_meta.snapshot.json";
  if (pathExists(packagePath, imageMetaPath)) {
    rows.set(imageMetaPath, "Template metadata snapshot used by generated cards.");
  }
  for (const dir of ["adapter", "bot-runtime", "feishu-host", "sidecar-long-connection"]) {
    const absoluteDir = path.join(packagePath, dir);
    if (!fs.existsSync(absoluteDir) || !fs.statSync(absoluteDir).isDirectory()) continue;
    for (const filePath of listPackageFiles(absoluteDir)) {
      const relativePath = toForwardSlash(path.join(dir, filePath));
      if (!isExcluded(relativePath)) {
        rows.set(relativePath, generatedClosureReason(dir));
      }
    }
  }
  return Array.from(rows.entries());
}

function optionalHandoffFiles(packagePath: string): HandoffFileDefinition[] {
  return OPTIONAL_EVIDENCE_FILES.filter(([filePath]) => pathExists(packagePath, filePath));
}

function generatedClosureReason(dir: string): string {
  if (dir === "adapter") return "Generated adapter runtime closure.";
  if (dir === "bot-runtime") return "Generated standalone reference runtime closure.";
  if (dir === "feishu-host") return "Generated self-hosted Feishu host module closure.";
  return "Generated sidecar or gateway host contract closure.";
}

function fileRow(packagePath: string, relativePath: string, reason: string): HandoffFile {
  return {
    path: relativePath,
    present: pathExists(packagePath, relativePath),
    reason,
  };
}

function pathExists(packagePath: string, relativePath: string): boolean {
  if (relativePath.includes("*")) {
    const dir = path.dirname(relativePath);
    const basename = path.basename(relativePath).replace(/\*/g, "");
    const absoluteDir = path.join(packagePath, dir);
    return fs.existsSync(absoluteDir) && fs.readdirSync(absoluteDir).some((entry) => entry.endsWith(basename));
  }
  return fs.existsSync(path.join(packagePath, relativePath));
}

function copyHandoffPackage(
  packagePath: string,
  targetPath: string,
  manifest: HandoffManifest,
  generatedManifestFiles: string[],
): number {
  assertCopyTarget(packagePath, targetPath);
  fs.mkdirSync(targetPath, { recursive: true });

  const relativeFiles = new Set([
    ...manifest.recommended_files.filter((item) => item.present).map((item) => item.path),
    ...manifest.optional_evidence_files.filter((item) => item.present).map((item) => item.path),
  ]);
  for (const generatedFile of generatedManifestFiles) {
    const relative = toRelativeInside(packagePath, generatedFile);
    if (relative) relativeFiles.add(relative);
  }

  assertNoSensitiveLeaks(packagePath, Array.from(relativeFiles).sort());
  let copied = 0;
  for (const relativePath of Array.from(relativeFiles).sort()) {
    if (isExcluded(relativePath)) continue;
    const source = path.join(packagePath, relativePath);
    if (!fs.existsSync(source) || fs.statSync(source).isDirectory()) continue;
    const target = path.join(targetPath, relativePath);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(source, target);
    copied += 1;
  }
  return copied;
}

function assertNoSensitiveLeaks(packagePath: string, relativeFiles: string[]): void {
  const sensitiveValues = collectSensitiveValues(packagePath);
  if (!sensitiveValues.length) return;

  const leaks: Array<{ file: string; key: string; source: string }> = [];
  for (const relativePath of relativeFiles) {
    if (isExcluded(relativePath)) continue;
    const source = path.join(packagePath, relativePath);
    if (!fs.existsSync(source) || fs.statSync(source).isDirectory() || !isTextFile(relativePath)) continue;
    const content = fs.readFileSync(source, "utf8");
    for (const item of sensitiveValues) {
      if (containsSensitiveValue(content, item.value)) {
        leaks.push({ file: relativePath, key: item.key, source: item.source });
      }
    }
  }

  if (leaks.length) {
    const details = leaks
      .map((item) => `${item.file} contains ${item.key} from ${item.source}`)
      .join("; ");
    throw new Error(`Refusing sanitized handoff copy because copied files contain local secret values: ${details}. Remove or redact these values before rerunning handoff.`);
  }
}

function assertHandoffCheckPassed(packagePath: string, manifest: HandoffManifest): void {
  const missingRecommended = manifest.recommended_files.filter((item) => !item.present);
  const presentExcluded = manifest.excluded_paths.filter((item) => item.present);
  const genericSecrets = scanGenericSecretLiterals(packagePath);
  const unredactedEvidence = scanUnredactedSharedEvidence(packagePath);
  const nonStrictConfigureCommands = scanNonStrictConfigureCommands(packagePath);
  const missingConfigureDryRunGuidance = scanMissingConfigureDryRunGuidance(packagePath);
  const missingInitLocalGuidance = scanMissingInitLocalGuidance(packagePath);
  const missingPermissionConfirmationGuidance = scanMissingPermissionConfirmationGuidance(packagePath);
  const missingDoctorProbeTargetGateGuidance = scanMissingDoctorProbeTargetGateGuidance(packagePath);
  const stalePackagePathReferences = scanStalePackagePathReferences(packagePath);
  const failures: string[] = [];

  if (missingRecommended.length) {
    failures.push(`missing recommended files: ${missingRecommended.map((item) => item.path).join(", ")}`);
  }
  if (presentExcluded.length) {
    failures.push(`excluded paths are present: ${presentExcluded.map((item) => item.path).join(", ")}`);
  }
  if (genericSecrets.length) {
    failures.push(`potential secret literals found: ${genericSecrets.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (unredactedEvidence.length) {
    failures.push(`unredacted shared evidence rows found: ${unredactedEvidence.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (nonStrictConfigureCommands.length) {
    failures.push(`non-strict configure commands found: ${nonStrictConfigureCommands.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (missingConfigureDryRunGuidance.length) {
    failures.push(`missing configure dry-run guidance: ${missingConfigureDryRunGuidance.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (missingInitLocalGuidance.length) {
    failures.push(`missing init-local guidance: ${missingInitLocalGuidance.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (missingPermissionConfirmationGuidance.length) {
    failures.push(`missing permission confirmation guidance: ${missingPermissionConfirmationGuidance.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (missingDoctorProbeTargetGateGuidance.length) {
    failures.push(`missing doctor live target gate guidance: ${missingDoctorProbeTargetGateGuidance.map((item) => `${item.path} (${item.kind})`).join(", ")}`);
  }
  if (stalePackagePathReferences.length) {
    failures.push(`stale package path references found: ${stalePackagePathReferences.map((item) => `${item.path} (${item.kind}: ${item.value})`).join(", ")}`);
  }

  if (failures.length) {
    throw new Error(`Handoff check failed for ${packagePath}: ${failures.join("; ")}.`);
  }
}

function scanGenericSecretLiterals(packagePath: string): GenericSecretFinding[] {
  const findings: GenericSecretFinding[] = [];
  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    for (const { kind, pattern } of GENERIC_SECRET_PATTERNS) {
      pattern.lastIndex = 0;
      if (pattern.test(content)) {
        findings.push({ path: relativePath, kind });
      }
    }
  }
  return findings;
}

function scanUnredactedSharedEvidence(packagePath: string): SharedEvidenceFinding[] {
  const relativePath = "level2_evidence_draft.md";
  const filePath = path.join(packagePath, relativePath);
  if (!fs.existsSync(filePath)) return [];

  const findings: SharedEvidenceFinding[] = [];
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const finding = findUnredactedManualEvidenceRow(line);
    if (finding) findings.push({ path: relativePath, kind: finding });
  }
  return dedupeEvidenceFindings(findings);
}

function findUnredactedManualEvidenceRow(line: string): string {
  if (!line.trim().startsWith("|")) return "";
  const cells = line.split("|");
  if (cells.length < 5) return "";
  const suppliedValue = (cells[2] || "").trim();
  const sourceIndex = cells.length - 2;
  const source = (cells[sourceIndex] || "").trim();
  if (!isManualEvidenceSource(source)) return "";
  if (!/provided \(redacted in shared draft\)/i.test(suppliedValue)) return "manual_evidence_value_not_redacted";
  if (/manual evidence file/i.test(source) && !/manual evidence file \(redacted path\)/i.test(source)) {
    return "manual_evidence_source_path_not_redacted";
  }
  return "";
}

function dedupeEvidenceFindings(findings: SharedEvidenceFinding[]): SharedEvidenceFinding[] {
  const seen = new Set<string>();
  return findings.filter((item) => {
    const id = `${item.path}\0${item.kind}`;
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function scanNonStrictConfigureCommands(packagePath: string): HandoffInstructionFinding[] {
  const findings: HandoffInstructionFinding[] = [];
  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    if (containsNonStrictConfigureCommand(content)) {
      findings.push({ path: relativePath, kind: "configure_without_strict" });
    }
  }
  return dedupeInstructionFindings(findings);
}

function scanMissingConfigureDryRunGuidance(packagePath: string): HandoffInstructionFinding[] {
  let hasConfigureCommand = false;
  let hasDryRunConfigureCommand = false;
  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    for (const line of content.split(/\r?\n/)) {
      if (!isConfigureCommandLine(line)) continue;
      hasConfigureCommand = true;
      if (containsConfigureDryRun(line)) {
        hasDryRunConfigureCommand = true;
      }
    }
  }
  if (!hasConfigureCommand || hasDryRunConfigureCommand) return [];
  return [{ path: "package", kind: "configure_dry_run_missing" }];
}

function scanMissingInitLocalGuidance(packagePath: string): HandoffInstructionFinding[] {
  let hasContextTemplate = false;
  let hasInitLocalContextReplyCommand = false;
  for (const relativePath of listPackageFiles(packagePath)) {
    if (relativePath === "feishu_context.template.json") {
      hasContextTemplate = true;
    }
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    if (containsInitLocalContextReplyCommand(content)) {
      hasInitLocalContextReplyCommand = true;
    }
  }
  if (!hasContextTemplate || hasInitLocalContextReplyCommand) return [];
  return [{ path: "package", kind: "init_local_context_reply_missing" }];
}

function scanMissingPermissionConfirmationGuidance(packagePath: string): HandoffInstructionFinding[] {
  if (!replyTemplateHasPermissionConfirmations(packagePath)) return [];
  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    if (/Permission confirmations/i.test(content)) return [];
  }
  return [{ path: "package", kind: "permission_confirmation_summary_missing" }];
}

function scanMissingDoctorProbeTargetGateGuidance(packagePath: string): HandoffInstructionFinding[] {
  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const content = fs.readFileSync(filePath, "utf8");
    if (containsDoctorProbeTargetGateCommand(content)) return [];
  }
  return [{ path: "package", kind: "doctor_probe_target_gate_missing" }];
}

function containsInitLocalContextReplyCommand(content: string): boolean {
  return content
    .split(/\r?\n/)
    .some((line) => /\binit-local\b/.test(line) && /(^|[\s"`'])--context(?=[\s"`',.]|$)/.test(line) && /(^|[\s"`'])--reply(?=[\s"`',.]|$)/.test(line));
}

function containsDoctorProbeTargetGateCommand(content: string): boolean {
  return content
    .split(/\r?\n/)
    .some((line) => isDoctorCommandLine(line)
      && /(^|[\s"`'])--gate(?=[\s"`',.]|$)/.test(line)
      && /(^|[\s"`'])--probe-target(?=[\s"`',.]|$)/.test(line));
}

function replyTemplateHasPermissionConfirmations(packagePath: string): boolean {
  const templatePath = path.join(packagePath, "feishu_context.reply.template.json");
  if (!fs.existsSync(templatePath)) return false;
  try {
    const parsed = readJsonFile<unknown>(templatePath);
    if (!isRecord(parsed) || !Array.isArray(parsed.permission_confirmations)) return false;
    return parsed.permission_confirmations.some((item) => isRecord(item) && typeof item.item === "string" && item.item.trim());
  } catch {
    return false;
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value && typeof value === "object" && !Array.isArray(value));
}

function containsNonStrictConfigureCommand(content: string): boolean {
  return content
    .split(/\r?\n/)
    .some((line) => isConfigureCommandLine(line) && !/(^|[\s"`'])--strict(?=[\s"`',.]|$)/.test(line));
}

function containsConfigureDryRun(line: string): boolean {
  return /(^|[\s"`'])--dry-run(?=[\s"`',.]|$)/.test(line) || /(^|[\s"`'])--dryRun(?=[\s"`',.]|$)/.test(line);
}

function isConfigureCommandLine(line: string): boolean {
  const trimmed = line.trim();
  if (!trimmed || !/\bnode\s+/.test(trimmed) || !/\bconfigure\b/.test(trimmed)) return false;
  return /(?:dist\/index\.js|dist\\index\.js|index\.js|\$env:LARK_DEPLOYER_CLI)/.test(trimmed);
}

function isDoctorCommandLine(line: string): boolean {
  const trimmed = line.trim();
  if (!trimmed || !/\bnode\s+/.test(trimmed) || !/\bdoctor\b/.test(trimmed)) return false;
  return /(?:dist\/index\.js|dist\\index\.js|index\.js|\$env:LARK_DEPLOYER_CLI)/.test(trimmed);
}

function dedupeInstructionFindings(findings: HandoffInstructionFinding[]): HandoffInstructionFinding[] {
  const seen = new Set<string>();
  return findings.filter((item) => {
    const id = `${item.path}\0${item.kind}`;
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function scanStalePackagePathReferences(packagePath: string): StalePackagePathFinding[] {
  const findings: StalePackagePathFinding[] = [];
  const contextPath = path.join(packagePath, "feishu_context.template.json");
  if (fs.existsSync(contextPath)) {
    try {
      const context = readJsonFile<Partial<ContextTemplate>>(contextPath);
      const hint = context.handoff_request?.generated_package_hint;
      if (typeof hint === "string" && hint.trim() && !packageReferenceMatchesCurrent(hint, packagePath)) {
        findings.push({ path: "feishu_context.template.json", kind: "generated_package_hint_stale", value: hint });
      }
    } catch {
      // Other commands surface malformed context files; stale path scanning stays best-effort.
    }
  }

  for (const relativePath of listPackageFiles(packagePath)) {
    if (isExcluded(relativePath) || !isTextFile(relativePath)) continue;
    const filePath = path.join(packagePath, relativePath);
    const candidates: string[] = [];
    collectPathLikeMatches(fs.readFileSync(filePath, "utf8"), candidates);
    for (const candidate of uniquePathCandidates(candidates, "")) {
      if (!packageReferenceMatchesCurrent(candidate, packagePath)) {
        findings.push({ path: relativePath, kind: "stale_package_path", value: candidate });
      }
    }
  }

  return dedupeStalePackagePathFindings(findings);
}

function packageReferenceMatchesCurrent(reference: string, packagePath: string): boolean {
  const trimmed = reference.trim().replace(/[\\\/]+$/, "");
  if (!trimmed) return true;

  const normalizedReference = normalizePathCandidate(trimmed);
  const normalizedPackagePath = normalizePathCandidate(packagePath);
  if (normalizedReference === normalizedPackagePath) return true;

  if (isDefaultGeneratedPackageReference(trimmed, packagePath)) return true;

  if (!path.isAbsolute(trimmed)) {
    if (normalizePathCandidate(path.resolve(trimmed)) === normalizedPackagePath) return true;
    if (normalizePathCandidate(path.resolve(packagePath, trimmed)) === normalizedPackagePath) return true;
  }

  return false;
}

function isDefaultGeneratedPackageReference(reference: string, packagePath: string): boolean {
  return normalizePathCandidate(reference) === "generated\\image-agent-web-lark"
    && path.basename(packagePath).toLowerCase() === "image-agent-web-lark"
    && path.basename(path.dirname(packagePath)).toLowerCase() === "generated";
}

function dedupeStalePackagePathFindings(findings: StalePackagePathFinding[]): StalePackagePathFinding[] {
  const seen = new Set<string>();
  return findings.filter((item) => {
    const id = `${item.path}\0${item.kind}\0${normalizePathCandidate(item.value)}`;
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function listPackageFiles(packagePath: string): string[] {
  const files: string[] = [];
  const stack = [packagePath];
  while (stack.length) {
    const current = stack.pop() || "";
    if (!current || !fs.existsSync(current)) continue;
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const absolute = path.join(current, entry.name);
      const relative = toForwardSlash(path.relative(packagePath, absolute));
      if (entry.isDirectory()) {
        if (!isExcluded(relative)) {
          stack.push(absolute);
        }
        continue;
      }
      if (entry.isFile()) {
        files.push(relative);
      }
    }
  }
  return files.sort();
}

function collectSensitiveValues(packagePath: string): SensitiveValue[] {
  const values: SensitiveValue[] = [];
  const envPath = path.join(packagePath, "bot-runtime", ".env");
  const env = readEnvFileIfExists(envPath);
  for (const key of ["APP_SECRET", "VERIFICATION_TOKEN", "ENCRYPT_KEY", "DEBUG_ACCESS_TOKEN"]) {
    addSensitiveValue(values, key, env[key], "bot-runtime/.env");
  }

  collectSensitiveContextValues(values, packagePath, "feishu_context.local.json");
  collectSensitiveContextValues(values, packagePath, "feishu_context.template.json");
  return dedupeSensitiveValues(values);
}

function collectSensitiveContextValues(values: SensitiveValue[], packagePath: string, relativePath: string): void {
  const filePath = path.join(packagePath, relativePath);
  if (!fs.existsSync(filePath)) return;
  let context: SensitiveContext;
  try {
    context = readJsonFile<SensitiveContext>(filePath);
  } catch {
    return;
  }

  addSensitiveValue(values, "feishu_app.app_secret", context.feishu_app?.app_secret, relativePath);
  addSensitiveValue(values, "feishu_app.verification_token", context.feishu_app?.verification_token, relativePath);
  addSensitiveValue(values, "feishu_app.encrypt_key", context.feishu_app?.encrypt_key, relativePath);
  addSensitiveValue(values, "runtime_config.debug_access_token", context.runtime_config?.debug_access_token, relativePath);
}

function addSensitiveValue(values: SensitiveValue[], key: string, value: unknown, source: string): void {
  if (typeof value !== "string") return;
  const trimmed = value.trim();
  if (trimmed.length < 6 || looksLikePlaceholder(trimmed)) return;
  values.push({ key, value: trimmed, source });
}

function containsSensitiveValue(content: string, value: string): boolean {
  if (!/^[A-Za-z0-9_=-]+$/.test(value)) return content.includes(value);
  const escaped = escapeRegExp(value);
  return new RegExp(`(^|[^A-Za-z0-9_=-])${escaped}($|[^A-Za-z0-9_=-])`).test(content);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function looksLikePlaceholder(value: string): boolean {
  return /^<.*>$/.test(value) || value.toLowerCase().includes("placeholder");
}

function dedupeSensitiveValues(values: SensitiveValue[]): SensitiveValue[] {
  const seen = new Set<string>();
  return values.filter((item) => {
    const id = `${item.key}\0${item.value}\0${item.source}`;
    if (seen.has(id)) return false;
    seen.add(id);
    return true;
  });
}

function isTextFile(relativePath: string): boolean {
  return /\.(json|md|txt|ts|js|mjs|cjs|yml|yaml|toml|env|gitignore)$/i.test(relativePath)
    || !path.extname(relativePath);
}

function assertCopyTarget(packagePath: string, targetPath: string): void {
  if (path.resolve(packagePath) === path.resolve(targetPath)) {
    throw new Error("--copy-to must not point at the generated package itself.");
  }
  const relativeFromPackage = path.relative(packagePath, targetPath);
  if (relativeFromPackage && !relativeFromPackage.startsWith("..") && !path.isAbsolute(relativeFromPackage)) {
    throw new Error("--copy-to must not be inside the generated package; choose a separate empty directory.");
  }
  if (fs.existsSync(targetPath) && fs.readdirSync(targetPath).length > 0) {
    throw new Error(`--copy-to target already exists and is not empty: ${targetPath}`);
  }
}

function toRelativeInside(packagePath: string, filePath: string): string {
  const relative = path.relative(packagePath, filePath);
  if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) return "";
  return toForwardSlash(relative);
}

function isExcluded(relativePath: string): boolean {
  const normalized = toForwardSlash(relativePath);
  return normalized === "bot-runtime/.env"
    || normalized === "feishu_context.local.json"
    || normalized === "feishu_context.reply.local.json"
    || normalized === "feishu_context.reply.local.md"
    || normalized === "level2_manual_evidence.local.json"
    || normalized.startsWith("bot-runtime/node_modules/")
    || normalized === "bot-runtime/node_modules"
    || normalized.startsWith("bot-runtime/dist/")
    || normalized === "bot-runtime/dist"
    || normalized.startsWith("bot-runtime/tmp/")
    || normalized === "bot-runtime/tmp"
    || normalized === "bot-runtime/audit.log"
    || normalized.startsWith("bot-runtime/") && normalized.endsWith(".log")
    || normalized === "feishu-host/.env"
    || normalized.startsWith("feishu-host/.venv/")
    || normalized === "feishu-host/.venv"
    || normalized.startsWith("feishu-host/__pycache__/")
    || normalized === "feishu-host/__pycache__"
    || normalized.startsWith("feishu-host/") && normalized.endsWith(".pyc");
}

function toForwardSlash(value: string): string {
  return value.replace(/\\/g, "/");
}

function buildWarnings(recommendedFiles: HandoffFile[], excludedPaths: HandoffFile[]): string[] {
  const warnings: string[] = [];
  const missingRecommended = recommendedFiles.filter((item) => !item.present);
  if (missingRecommended.length) {
    warnings.push(`Missing recommended files: ${missingRecommended.map((item) => item.path).join(", ")}.`);
  }
  const presentExcluded = excludedPaths.filter((item) => item.present);
  if (presentExcluded.length) {
    warnings.push(`Excluded local/sensitive paths currently exist and must not be copied: ${presentExcluded.map((item) => item.path).join(", ")}.`);
  }
  return warnings;
}

function buildHandoffMarkdown(manifest: HandoffManifest): string {
  return `# Handoff Manifest

- Generated at: ${manifest.generated_at}
- Package: ${manifest.package_path}
- Target service: ${manifest.target_service}

## Recommended Files

${table(manifest.recommended_files)}

## Optional Evidence Files

${table(manifest.optional_evidence_files)}

## Excluded Paths

Do not copy these into a shared package unless a reviewer explicitly asks for them.

${table(manifest.excluded_paths)}

## Warnings

${manifest.warnings.length ? manifest.warnings.map((item) => `- ${item}`).join("\n") : "- none"}

## Next Steps

${manifest.next_steps.map((item) => `- ${item}`).join("\n")}
`;
}

function table(rows: HandoffFile[]): string {
  return [
    "| Present | Path | Reason |",
    "| --- | --- | --- |",
    ...rows.map((row) => `| ${row.present ? "yes" : "no"} | \`${row.path}\` | ${row.reason.replace(/\|/g, "\\|")} |`),
  ].join("\n");
}

function printHandoffSummary(manifest: HandoffManifest, outFile: string, markdownFile: string): void {
  const missing = manifest.recommended_files.filter((item) => !item.present).length;
  const excludedPresent = manifest.excluded_paths.filter((item) => item.present).length;
  console.log(`Handoff manifest written to ${outFile}`);
  console.log(`Handoff checklist written to ${markdownFile}`);
  console.log(`Recommended files missing: ${missing}`);
  console.log(`Excluded paths currently present: ${excludedPresent}`);
  if (manifest.warnings.length) {
    console.log(`Warnings: ${manifest.warnings.length}`);
  }
}
