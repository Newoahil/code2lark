function quoteCommandArg(value: string): string {
  if (!value) return "\"\"";
  if (/[\s"'#]/.test(value)) return JSON.stringify(value);
  return value;
}

function refreshCopiedVerificationArtifacts(packagePath: string, sourcePackagePathCandidates: string[]): void {
  const verificationReportPath = path.join(packagePath, "verification_report.json");
  if (fs.existsSync(verificationReportPath)) {
    const report = readJsonFile<unknown>(verificationReportPath);
    writeJson(verificationReportPath, replacePackagePathStrings(report, sourcePackagePathCandidates, packagePath));
  }
  for (const relativePath of ["verification_report.md", "level2_evidence_draft.md"]) {
    const filePath = path.join(packagePath, relativePath);
    if (!fs.existsSync(filePath)) continue;
    let content = replacePackagePathText(fs.readFileSync(filePath, "utf8"), sourcePackagePathCandidates, packagePath);
    if (relativePath === "level2_evidence_draft.md") {
      content = redactLegacyManualEvidenceDraft(content);
    }
    writeText(filePath, content);
  }
}

function redactLegacyManualEvidenceDraft(content: string): string {
  return content
    .split(/\r?\n/)
    .map((line) => redactLegacyManualEvidenceRow(line))
    .join("\n");
}

function redactLegacyManualEvidenceRow(line: string): string {
  if (!line.trim().startsWith("|")) return line;
  const cells = line.split("|");
  if (cells.length < 5) return line;
  const sourceIndex = cells.length - 2;
  const source = cells[sourceIndex] || "";
  if (!isManualEvidenceSource(source)) return line;
  cells[2] = " provided (redacted in shared draft) ";
  cells[sourceIndex] = ` ${redactedManualEvidenceSource(source)} `;
  return cells.join("|");
}

function isManualEvidenceSource(source: string): boolean {
  return /manual evidence file|manual CLI options/i.test(source);
}

function redactedManualEvidenceSource(source: string): string {
  const hasFile = /manual evidence file/i.test(source);
  const hasCli = /manual CLI options/i.test(source);
  if (hasFile && hasCli) return "manual evidence file (redacted path) + manual CLI options";
  if (hasFile) return "manual evidence file (redacted path)";
  if (hasCli) return "manual CLI options";
  return "manual evidence";
}

function collectSourcePackagePathCandidates(packagePath: string): string[] {
  const candidates: string[] = [];
  const verificationReportPath = path.join(packagePath, "verification_report.json");
  if (fs.existsSync(verificationReportPath)) {
    try {
      const report = readJsonFile<unknown>(verificationReportPath);
      collectPathLikeStrings(report, candidates);
    } catch {
      // Ignore stale or malformed optional evidence; handoff --check will still scan copied text.
    }
  }
  const contextPath = path.join(packagePath, "feishu_context.template.json");
  if (fs.existsSync(contextPath)) {
    try {
      const context = readJsonFile<Partial<ContextTemplate>>(contextPath);
      const hint = context.handoff_request?.generated_package_hint;
      if (typeof hint === "string") candidates.push(hint);
    } catch {
      // Ignore malformed optional context here; other commands surface parse failures.
    }
  }

  for (const relativePath of ["verification_report.md", "level2_evidence_draft.md"]) {
    const filePath = path.join(packagePath, relativePath);
    if (!fs.existsSync(filePath)) continue;
    collectPathLikeMatches(fs.readFileSync(filePath, "utf8"), candidates);
  }

  return uniquePathCandidates(candidates, packagePath);
}

function collectPathLikeStrings(value: unknown, output: string[]): void {
  if (typeof value === "string") {
    collectPathLikeMatches(value, output);
    return;
  }
  if (Array.isArray(value)) {
    for (const item of value) collectPathLikeStrings(item, output);
    return;
  }
  if (value && typeof value === "object") {
    for (const item of Object.values(value)) collectPathLikeStrings(item, output);
  }
}

function collectPathLikeMatches(value: string, output: string[]): void {
  const windowsPathPattern = /[A-Za-z]:\\[^\r\n|`"]*?(?:image-agent-web-lark|[A-Za-z0-9_-]+-lark)(?=\\|$|[\s\r\n|`"])/g;
  for (const match of value.matchAll(windowsPathPattern)) {
    output.push(match[0]);
  }
  if (/\bgenerated\\image-agent-web-lark\b/.test(value)) {
    output.push("generated\\image-agent-web-lark");
  }
}

function uniquePathCandidates(candidates: string[], packagePath: string): string[] {
  const normalizedPackagePath = normalizePathCandidate(packagePath);
  const seen = new Set<string>();
  return candidates
    .map((candidate) => candidate.trim().replace(/[\\\/]+$/, ""))
    .filter((candidate) => candidate && normalizePathCandidate(candidate) !== normalizedPackagePath)
    .filter((candidate) => {
      const normalized = normalizePathCandidate(candidate);
      if (seen.has(normalized)) return false;
      seen.add(normalized);
      return true;
    })
    .sort((a, b) => b.length - a.length);
}

function normalizePathCandidate(value: string): string {
  return value.replace(/\//g, "\\").replace(/[\\]+$/g, "").toLowerCase();
}

function replacePackagePathStrings(value: unknown, sourcePackagePathCandidates: string[], packagePath: string): unknown {
  if (typeof value === "string") return replacePackagePathText(value, sourcePackagePathCandidates, packagePath);
  if (Array.isArray(value)) return value.map((item) => replacePackagePathStrings(item, sourcePackagePathCandidates, packagePath));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [
      key,
      replacePackagePathStrings(item, sourcePackagePathCandidates, packagePath),
    ]));
  }
  return value;
}

function replacePackagePathText(content: string, sourcePackagePathCandidates: string[], packagePath: string): string {
  let updated = content;
  for (const candidate of sourcePackagePathCandidates) {
    updated = updated.split(candidate).join(packagePath);
    updated = updated.split(candidate.replace(/\\/g, "/")).join(packagePath.replace(/\\/g, "/"));
  }
  return updated;
}

function refreshCopiedLevel2RecordPaths(packagePath: string): void {
  const recordPath = path.join(packagePath, "level2_verification_record.md");
  if (!fs.existsSync(recordPath)) return;

  const replacements = [
    ["Generated package path", packagePath],
    ["`verification_report.md` path", path.join(packagePath, "verification_report.md")],
  ] as const;
  let record = fs.readFileSync(recordPath, "utf8");
  for (const [field, value] of replacements) {
    record = replaceRecordField(record, field, value);
  }
  record = refreshLevel2RecordCliGuidance(record);
  writeText(recordPath, record);
}

function replaceRecordField(record: string, field: string, value: string): string {
  const pattern = new RegExp(`^(-[^\\S\\r\\n]*${escapeRegExp(field)}:[^\\S\\r\\n]*)([^\\r\\n]*)$`, "im");
  return record.replace(pattern, (_line, prefix: string) => `${prefix.replace(/[^\S\r\n]*$/, " ")}${value}`);
}

