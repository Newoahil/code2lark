export async function handoffCommand(args: string[], options: Record<string, string | boolean>): Promise<void> {
  const packageArg = args[0];
  if (!packageArg) {
    throw new Error("Usage: lark-deployer handoff <generated-package> [--out <file>] [--copy-to <dir>] [--check]");
  }

  const packagePath = path.resolve(packageArg);
  const manifest = buildHandoffManifest(packagePath);
  const outFile = path.resolve(getStringOption(options, "out", path.join(packagePath, "handoff_manifest.json")));
  const markdownFile = outFile.replace(/\.json$/i, ".md");
  const copyTo = getStringOption(options, "copy-to", getStringOption(options, "copyTo", ""));
  const check = hasOption(options, "check");

  writeJson(outFile, manifest);
  writeText(markdownFile, buildHandoffMarkdown(manifest));
  if (copyTo) {
    const copyTargetPath = path.resolve(copyTo);
    const copied = copyHandoffPackage(packagePath, copyTargetPath, manifest, [outFile, markdownFile]);
    refreshCopiedHandoffReports(copyTargetPath);
    console.log(`Sanitized handoff copy written to ${copyTargetPath}`);
    console.log(`Copied files: ${copied}`);
    console.log("Refreshed context, verification, evidence, handoff, doctor, and Level 2 path references inside the copied package.");
  }
  if (check) {
    const checkPath = copyTo ? path.resolve(copyTo) : packagePath;
    const checkManifest = copyTo ? buildHandoffManifest(checkPath) : manifest;
    assertHandoffCheckPassed(checkPath, checkManifest);
    console.log(`Handoff check passed for ${checkPath}`);
  }
  printHandoffSummary(manifest, outFile, markdownFile);
}

function refreshCopiedHandoffReports(packagePath: string): void {
  const sourcePackagePathCandidates = collectSourcePackagePathCandidates(packagePath);
  refreshCopiedContextFiles(packagePath);
  refreshCopiedVerificationArtifacts(packagePath, sourcePackagePathCandidates);
  refreshCopiedLevel2RecordPaths(packagePath);
  const readinessSummary = buildReadinessSummary(packagePath, {});
  writeText(path.join(packagePath, "handoff_status.md"), buildReadinessMarkdown(readinessSummary));
  writeDoctorReportFiles(packagePath, path.join(packagePath, "doctor_report.json"));
  const targetManifest = buildHandoffManifest(packagePath);
  writeJson(path.join(packagePath, "handoff_manifest.json"), targetManifest);
  writeText(path.join(packagePath, "handoff_manifest.md"), buildHandoffMarkdown(targetManifest));
}

function refreshCopiedContextFiles(packagePath: string): void {
  const contextPath = path.join(packagePath, "feishu_context.template.json");
  if (!fs.existsSync(contextPath)) return;

  const context = readJsonFile<ContextTemplate>(contextPath);
  const refreshed: ContextTemplate = {
    ...context,
    handoff_request: {
      ...context.handoff_request,
      generated_package_hint: packagePath,
      verification_commands: copiedPackageCommands(),
      command_sets: copiedPackageCommandSets(packagePath),
    },
  };
  writeJson(contextPath, refreshed);
  writeText(path.join(packagePath, "feishu_context.template.md"), buildContextMarkdown(refreshed));
  writeText(path.join(packagePath, "feishu_context.request.md"), buildContextRequestMarkdown(refreshed));
  const replyTemplate = buildContextReplyTemplate(refreshed);
  writeJson(path.join(packagePath, "feishu_context.reply.template.json"), replyTemplate);
  writeText(path.join(packagePath, "feishu_context.reply.template.md"), buildContextReplyMarkdown(replyTemplate));
}

